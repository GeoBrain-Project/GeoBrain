"""
Walker Lake dataset (synthetic approximation).

Returns the classic 2-D benchmark with 470 points and the two
correlated variables ``V`` and ``U``. Deterministic via fixed seed
``42``.

This is a *synthetic approximation* of the original Isaaks &
Srivastava (1989) dataset: same column names and shape, but the
underlying field is generated by sinusoid + noise rather than the
real Walker-Lake DEM.

Author: Mingliang Liu (mingliangliu@sdu.edu.cn)
Version: 0.2.0
"""

from __future__ import annotations

import numpy as np

from geobrain.geomodel.frames._arrays import as_float_array, column_stack_float
from geobrain.geomodel.frames import GeoFrame, GeoPoints


def walker_lake() -> GeoFrame:
    """Return the Walker Lake synthetic GeoFrame (470 rows, V & U columns)."""
    rng = np.random.default_rng(42)
    n = 470
    x = as_float_array(rng.uniform(0.0, 300.0, n))
    y = as_float_array(rng.uniform(0.0, 300.0, n))
    V = as_float_array(
        50.0 + 30.0 * np.sin(x / 50.0) * np.cos(y / 40.0) + rng.normal(0.0, 10.0, n)
    )
    U = as_float_array(20.0 + V * 0.3 + rng.normal(0.0, 5.0, n))
    coords = column_stack_float([x, y])
    return GeoFrame(GeoPoints(coords), properties={"V": V, "U": U})


__all__ = ["walker_lake"]
