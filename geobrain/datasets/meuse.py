"""
Meuse dataset (synthetic approximation).

River-flood-plain
heavy-metal benchmark, 155 points with columns ``Zn``, ``Cu``, ``Pb``,
``Cd`` and the auxiliary ``dist_river`` covariate. Deterministic
via fixed seed ``55``.

Synthetic approximation: coordinates are in the same UTM-style
range as the published Burrough & McDonnell (2000) Meuse dataset,
but the metal concentrations are generated by an exponential decay
with distance to a single synthetic river point.

Author: Mingliang Liu (mingliangliu@sdu.edu.cn)
Version: 0.2.0
"""

from __future__ import annotations
import numpy as np

from geobrain.geomodel.frames._arrays import as_float_array, column_stack_float
from geobrain.geomodel.frames import GeoFrame, GeoPoints


def meuse() -> GeoFrame:
    """Return the Meuse synthetic GeoFrame (155 rows, 4 metals + dist_river)."""
    rng = np.random.default_rng(55)
    n = 155
    x = as_float_array(rng.uniform(178000.0, 182000.0, n))
    y = as_float_array(rng.uniform(329000.0, 334000.0, n))

    dist_river = as_float_array(
        np.sqrt((x - 179000.0) ** 2 + (y - 331000.0) ** 2) / 5000.0
    )
    dist_river = as_float_array(np.clip(dist_river, 0.0, 1.0))

    Zn = as_float_array(np.maximum(10.0, 1000.0 * np.exp(-2.0 * dist_river) + rng.normal(0.0, 100.0, n)))
    Cu = as_float_array(np.maximum(5.0, 80.0 * np.exp(-1.5 * dist_river) + rng.normal(0.0, 15.0, n)))
    Pb = as_float_array(np.maximum(10.0, 300.0 * np.exp(-1.8 * dist_river) + rng.normal(0.0, 40.0, n)))
    Cd = as_float_array(np.maximum(0.1, 15.0 * np.exp(-2.5 * dist_river) + rng.normal(0.0, 2.0, n)))

    coords = column_stack_float([x, y])
    return GeoFrame(
        GeoPoints(coords),
        properties={
            "Zn": Zn, "Cu": Cu, "Pb": Pb, "Cd": Cd,
            "dist_river": dist_river,
        },
    )


__all__ = ["meuse"]
